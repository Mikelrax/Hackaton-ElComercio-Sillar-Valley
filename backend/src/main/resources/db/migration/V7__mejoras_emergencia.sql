CREATE TABLE emergency_claims (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id  BIGINT      NOT NULL REFERENCES emergency_reports (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_emergency_claims UNIQUE (report_id, user_id)
);

CREATE TABLE emergency_check_ins (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activation_id BIGINT      NOT NULL REFERENCES emergency_activations (id) ON DELETE CASCADE,
    user_id       BIGINT      NOT NULL REFERENCES users (id),
    status        VARCHAR(20) NOT NULL,
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_emergency_check_ins UNIQUE (activation_id, user_id)
);

