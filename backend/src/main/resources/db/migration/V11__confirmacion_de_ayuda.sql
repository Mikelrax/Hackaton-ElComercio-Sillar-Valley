ALTER TABLE posts ADD COLUMN fulfilled_at TIMESTAMPTZ;
ALTER TABLE help_responses ADD COLUMN accepted_at TIMESTAMPTZ;

UPDATE help_responses SET accepted_at = created_at WHERE status = 'ACCEPTED';

CREATE TABLE help_awards (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id     BIGINT      NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    helper_id   BIGINT      NOT NULL REFERENCES users (id),
    receiver_id BIGINT      NOT NULL REFERENCES users (id),
    points      INTEGER     NOT NULL,
    reason      VARCHAR(20),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_help_awards_post UNIQUE (post_id)
);

CREATE INDEX idx_help_awards_helper ON help_awards (helper_id, created_at);
CREATE INDEX idx_help_awards_created ON help_awards (created_at);
