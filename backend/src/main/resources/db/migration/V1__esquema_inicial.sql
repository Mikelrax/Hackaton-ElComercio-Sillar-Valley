-- Esquema inicial de AYNI (PostgreSQL). Debe coincidir con las entidades JPA (ddl-auto: validate).

CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name      VARCHAR(120) NOT NULL,
    phone          VARCHAR(15)  NOT NULL,
    email          VARCHAR(160),
    password_hash  VARCHAR(100) NOT NULL,
    role           VARCHAR(20)  NOT NULL,
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    ayni_points    INTEGER      NOT NULL DEFAULT 0,
    help_given     INTEGER      NOT NULL DEFAULT 0,
    help_received  INTEGER      NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_users_phone UNIQUE (phone),
    CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE TABLE posts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id       BIGINT        NOT NULL REFERENCES users (id),
    moderated_by_id BIGINT        REFERENCES users (id),
    type            VARCHAR(20)   NOT NULL,
    category        VARCHAR(30)   NOT NULL,
    title           VARCHAR(150)  NOT NULL,
    description     VARCHAR(2000) NOT NULL,
    neighborhood    VARCHAR(120),
    status          VARCHAR(20)   NOT NULL,
    moderation_note VARCHAR(500),
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_posts_status_created ON posts (status, created_at DESC);
CREATE INDEX idx_posts_author ON posts (author_id);

CREATE TABLE post_images (
    post_id   BIGINT      NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    file_name VARCHAR(60) NOT NULL
);
CREATE INDEX idx_post_images_post ON post_images (post_id);

CREATE TABLE help_responses (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    BIGINT        NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    helper_id  BIGINT        NOT NULL REFERENCES users (id),
    message    VARCHAR(1000) NOT NULL,
    status     VARCHAR(20)   NOT NULL,
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_response_post_helper UNIQUE (post_id, helper_id)
);
CREATE INDEX idx_responses_helper ON help_responses (helper_id);

CREATE TABLE reports (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id         BIGINT       NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    reporter_id     BIGINT       NOT NULL REFERENCES users (id),
    reason          VARCHAR(500) NOT NULL,
    status          VARCHAR(20)  NOT NULL,
    resolution_note VARCHAR(500),
    resolved_by_id  BIGINT       REFERENCES users (id),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    resolved_at     TIMESTAMPTZ
);
CREATE INDEX idx_reports_status ON reports (status, created_at);
