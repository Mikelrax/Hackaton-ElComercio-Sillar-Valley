CREATE TABLE emergency_activations (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title             VARCHAR(80)  NOT NULL,
    message           VARCHAR(500),
    active            BOOLEAN      NOT NULL DEFAULT TRUE,
    activated_by_id   BIGINT       NOT NULL REFERENCES users (id),
    activated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deactivated_by_id BIGINT       REFERENCES users (id),
    deactivated_at    TIMESTAMPTZ
);
CREATE INDEX idx_emergency_activations_active ON emergency_activations (active, activated_at DESC);

CREATE TABLE emergency_reports (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind         VARCHAR(20)      NOT NULL,
    category     VARCHAR(30)      NOT NULL,
    title        VARCHAR(150)     NOT NULL,
    people_count INTEGER          NOT NULL DEFAULT 1,
    severity     VARCHAR(10)      NOT NULL,
    status       VARCHAR(20)      NOT NULL,
    verified     BOOLEAN          NOT NULL DEFAULT FALSE,
    reporter_id  BIGINT           NOT NULL REFERENCES users (id),
    helper_id    BIGINT           REFERENCES users (id),
    neighborhood VARCHAR(120)     NOT NULL,
    latitude     DOUBLE PRECISION NOT NULL,
    longitude    DOUBLE PRECISION NOT NULL,
    created_at   TIMESTAMPTZ      NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ      NOT NULL DEFAULT now()
);
CREATE INDEX idx_emergency_reports_status ON emergency_reports (status, created_at DESC);

CREATE TABLE support_points (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(120)     NOT NULL,
    type          VARCHAR(20)      NOT NULL,
    neighborhood  VARCHAR(120)     NOT NULL,
    address       VARCHAR(200),
    latitude      DOUBLE PRECISION NOT NULL,
    longitude     DOUBLE PRECISION NOT NULL,
    is_open       BOOLEAN          NOT NULL DEFAULT TRUE,
    created_by_id BIGINT           NOT NULL REFERENCES users (id),
    created_at    TIMESTAMPTZ      NOT NULL DEFAULT now()
);
