CREATE TABLE neighborhoods (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(120) NOT NULL,
    sort_order INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT uq_neighborhoods_name UNIQUE (name)
);

