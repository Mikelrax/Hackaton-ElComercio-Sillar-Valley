CREATE TABLE businesses (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  VARCHAR(120)     NOT NULL,
    category_id           BIGINT           NOT NULL REFERENCES categories (id),
    description           VARCHAR(1000),
    phone                 VARCHAR(15),
    neighborhood          VARCHAR(120)     NOT NULL,
    reference             VARCHAR(200),
    latitude              DOUBLE PRECISION NOT NULL,
    longitude             DOUBLE PRECISION NOT NULL,
    opens_at              TIME,
    closes_at             TIME,
    open_days             VARCHAR(7),
    price_hint            VARCHAR(80),
    status                VARCHAR(20)      NOT NULL,
    created_by_id         BIGINT           NOT NULL REFERENCES users (id),
    moderated_by_id       BIGINT           REFERENCES users (id),
    moderation_note       VARCHAR(500),
    recommendations_count INTEGER          NOT NULL DEFAULT 0,
    good_price_count      INTEGER          NOT NULL DEFAULT 0,
    punctual_count        INTEGER          NOT NULL DEFAULT 0,
    reliable_count        INTEGER          NOT NULL DEFAULT 0,
    search_text           TEXT             NOT NULL DEFAULT '',
    created_at            TIMESTAMPTZ      NOT NULL DEFAULT now()
);
CREATE INDEX idx_businesses_status_category ON businesses (status, category_id);
CREATE INDEX idx_businesses_location ON businesses (latitude, longitude);

CREATE TABLE business_recommendations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT        NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    user_id     BIGINT        NOT NULL REFERENCES users (id),
    good_price  BOOLEAN       NOT NULL DEFAULT FALSE,
    punctual    BOOLEAN       NOT NULL DEFAULT FALSE,
    reliable    BOOLEAN       NOT NULL DEFAULT FALSE,
    comment     VARCHAR(500),
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_recommendation_business_user UNIQUE (business_id, user_id)
);
CREATE INDEX idx_recommendations_business ON business_recommendations (business_id, created_at DESC);
